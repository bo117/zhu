# 真过滤：自反条目（纯占位）+ 非纯中文
TYPOS = {k: v for k, v in TYPOS.items()
         if k and v and k != v and re.match(r"^[一-鿿]+$", k + v)}


def find_typos(text):
    """返回 [(错字, 正字)]，只报高置信命中"""
    return [(bad, good) for bad, good in TYPOS.items() if bad in text]


def fix_text(text, hits):
    for bad, good in hits:
        text = text.replace(bad, good)
    return text


