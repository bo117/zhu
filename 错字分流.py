# ── 关卡 3：脏尾巴清洗 ─────────────────────────────────────────────
# 原稿末尾印着「字数：625」—— 这类痕迹模型会原样学走，
# 生成出「……共690字」这种根本不属于正文的尾巴。
# ★ 踩过的坑：只按「行尾紧贴的 字数：NNN 」匹配，漏掉一半形态：
#     「字数统计（509）个生字」      「字数：590个字」（前面无换行）
#     「（字数：405个字 用时：30分钟）」  「（字数）（370）（个字）」
#     「字数：331（个字）」
#   改法：只要尾部区域出现字数标记，就从**那一行开头**整体切掉 ——
#   这些统计行本来就在正文之外，不属于文章内容。
_STAT_WORDS = ("字数", "生字", "个生字", "用时", "个词", "生词")
_DIGIT = re.compile(r'\d')


def _is_stat_line(line):
    """这一行像不像原稿末尾的字数统计栏？

    ★ 踩过的坑：用固定正则匹配「字数：NNN」，漏了一大片形态 ——
      「字数统计（509）个生字」 「字数：（405）用时：30分钟」
      「字数：“54,8个字”」 「字数；622」 「580【个字数流】」「二九八字数」
      —— 数字可能带千分位、可能没有、可能在标记前面、可能用分号。
      ★★ 误伤底线：正文里可能出现「美滋字数滋的」这种（小孩写错字）。
      所以不按格式认，按**特征**认：短行 + 高数字密度 + 命中统计词。
    """
    s = line.strip()
    if not s or len(s) > 45:
        return False
    has_word = any(w in s for w in _STAT_WORDS)
    n_digit = len(_DIGIT.findall(s))
    if not (has_word or n_digit):
        return False
    # 统计词的行：必须很短（<25字），否则是正文里提到「字数」
    if has_word and len(s) > 25:
        return False
    # 只有数字没有统计词的行：数字要占一半以上
    if not has_word and n_digit * 2 < len(s):
        return False
    return True


def strip_tail(text):
    """从尾部逐行删掉字数统计栏（连同其上方的空行）。只动尾部，不碰正文。"""
    lines = text.rstrip().split('\n')
    i = len(lines)
    while i > 0 and _is_stat_line(lines[i - 1]):
        i -= 1
    if i == len(lines):
        return text.rstrip()
    lines = lines[:i]
    while lines and not lines[-1].strip():
        lines.pop()
    return '\n'.join(lines).rstrip()


def has_tail(text):
    return strip_tail(text) != text.rstrip()


# ── 关卡 4：句级复读检测 ───────────────────────────────────────────
# 唯一字符率是伪指标（人名反复出现就误判），只认「整句重复」。
def _sentences(text):
    return [s.strip() for s in re.split(r'[。！？!?\n]', text)
            if len(s.strip()) >= 6]


def repeat_rate(text):
    ss = _sentences(text)
    if len(ss) < 4:
        return 0.0
    c = collections.Counter(ss)
    dup = sum(v - 1 for v in c.values() if v > 1)
    return dup / len(ss)


def suspicious_chars(text):
    """文中不在常用字集、且只出现 1~2 次的单字 -> 可疑错字，只标不改"""
    cnt = collections.Counter()
    for ch in text:
        if '一' <= ch <= '鿿' and ch not in COMMON \
                and _doc_freq.get(ch, 0) < MIN_DOC_FREQ:
            cnt[ch] += 1
    # 出现多次的多半是生僻但正确的字；只出现 1~2 次才可疑
    return [ch for ch, n in cnt.items() if n <= 2][:12]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--min-fix", type=int, default=1,
                    help="错字版语料至少几个错字（1=有一个就算）")
    ap.add_argument("--src", default=SRC)
    args = ap.parse_args()

    if not os.path.exists(args.src):
        print("✗ 找不到 %s（先跑 真人作文入库.py）" % args.src)
        return 1

    rows = [json.loads(l) for l in io.open(args.src, encoding="utf-8")
            if l.strip()]
    print("输入 %d 篇" % len(rows))

    clean, fixrows = [], []
    typo_stat = collections.Counter()
    n_with_typo = dirty_sus = n_tail = n_empty = dirty_rep = 0

    # 先扫一遍全语料的字文档频次，供关卡 2 兜底用
    _doc_freq.clear()
    for r in rows:
        _doc_freq.update(set(ch for ch in r["output"] if '一' <= ch <= '鿿'))
    print("语料字种类%d，其中 >=%d 篇出现的字%d 个（视为非错字）"
          % (len(_doc_freq), MIN_DOC_FREQ,
             sum(1 for n in _doc_freq.values() if n >= MIN_DOC_FREQ)))
    for r in rows:
        # 关卡 3 先做：脏尾巴是确定性缺陷，直接修，不丢样本
        body = strip_tail(r["output"])
        if has_tail(r["output"]):
            n_tail += 1
        if not body.strip():
            n_empty += 1
            continue
        hits = find_typos(body)
        if hits:
            n_with_typo += 1
            for bad, _ in hits:
                typo_stat[bad] += 1
            if len(hits) >= args.min_fix:
                fixrows.append({
                    "instruction": "下面这段文字里有错别字，请改正，保持原意和"
                                   "语气不变，直接给出改正后的全文。\n\n" + body,
                    "output": fix_text(body, hits),
                    "meta": {"typos": ["%s→%s" % (b, g) for b, g in hits],
                             "src": r.get("meta", {}).get("src", "真人作文"),
                             "title": r.get("meta", {}).get("title", "")},
                })
            continue
        # 关卡 2：表外可疑生僻字，只剔除不修
        sus = suspicious_chars(body)
        if sus:
            dirty_sus += 1
            continue
        # 关卡 4：整句复读
        if repeat_rate(body) > 0.15:
            dirty_rep += 1
            continue
        r2 = dict(r)
        r2["output"] = body
        clean.append(r2)

    with io.open(OUT_CLEAN, "w", encoding="utf-8", newline="\n") as f:
        for r in clean:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    os.makedirs(os.path.dirname(OUT_FIX), exist_ok=True)
    with io.open(OUT_FIX, "w", encoding="utf-8", newline="\n") as f:
        for r in fixrows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    n = len(rows)
    print("\n=== 分流结果 ===")
    print("干净集（**作文生成用，主料**）%4d 篇 (%.1f%%)"
          % (len(clean), 100 * len(clean) / n))
    print("改错字集（纠错任务用）        %4d 篇" % len(fixrows))
    print("表内错字但错字太少（丢弃）     %4d 篇" % (n_with_typo - len(fixrows)))
    print("表外可疑生僻字（只剔除不修）  %4d 篇" % dirty_sus)
    print("句级复读超15%%（剔除）         %4d 篇" % dirty_rep)
    print("篇末字数尾巴（已清洗不丢样本）%4d 篇" % n_tail)
    print("清洗后正文为空（丢弃）        %4d 篇" % n_empty)
    print("\n用户可见的干净集占比 %.1f%% —— 零高置信错字 + 零可疑生僻字 + 零复读"
          % (100 * len(clean) / n))
    print("TOP15 错字：")
    for bad, c in typo_stat.most_common(15):
        print("  %5d 次  %s → %s" % (c, bad, TYPOS[bad]))

    rep = {"total": n, "clean": len(clean), "fix_rows": len(fixrows),
           "with_typo": n_with_typo, "dirty_suspect": dirty_sus,
           "dirty_repeat": dirty_rep, "tail_stripped": n_tail,
           "top_typos": typo_stat.most_common(30),
           "typo_table_size": len(TYPOS),
           "common_chars": len(COMMON),
           "note": "干净集 = 零高置信错字 + 零可疑生僻字 + 零句级复读+ 已删字数尾巴"}
    os.makedirs(os.path.dirname(REPORT), exist_ok=True)
    json.dump(rep, io.open(REPORT, "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)
    print("\n-> %s\n-> %s\n-> %s" % (OUT_CLEAN, OUT_FIX, REPORT))
    return 0


