def _two_grams(s):
    return {s[i:i + 2] for i in range(len(s) - 1)}


def review_essay(essay):
    """点评作文：结构/语言/情感/立意四维打分 + 首尾呼应 + 点题 +
    具体润色示范，每项给分给理由"""
    words = len(essay.replace(" ", "").replace("\n", ""))
    paras = [p for p in essay.split("\n") if p.strip()]
    scores = {}
    notes_good, notes_bad = [], []

    # 0) 硬伤雷达：重复段落直接扣分
    seen = set()
    dup = 0
    for p in paras:
        key = p.strip()[:24]
        if key in seen:
            dup += 1
        seen.add(key)
    if dup:
        notes_bad.append("有 %d 个重复段落，行文大忌，需删改" % dup)

    # 1) 结构：段落数、开头结尾是否成形
    s = 10.0
    if len(paras) < 4:
        s -= 4
        notes_bad.append("段落太少（%d 段），文章至少要有起承转合四个层次"
                         % len(paras))
    if words < 300:
        s -= 3
        notes_bad.append("字数偏少（%d 字），细节展开不够" % words)
    head, tail = paras[0], paras[-1]
    if len(head) < 12:
        s -= 2
        notes_bad.append("开头太短太急，好开头要能勾住读者")
    if len(tail) < 12 or "。" not in tail:
        s -= 2
        notes_bad.append("结尾单薄，缺一句能收束全文的话")
    if re.search(r"[。！？]", head) and len(head) > 20:
        notes_good.append("开头成句成形，有画面感")
    if _two_grams(head) & _two_grams(tail):
        notes_good.append("首尾有呼应，结构完整")
    scores["结构"] = round(max(0, s), 1)

    # 2) 语言：修辞密度、长短句
    s = 10.0
    gold = sum(essay.count(m) for m in GOLD_MARKS)
    if gold >= 3:
        notes_good.append("修辞用得好（比喻/拟人出现 %d 处），语言有文采"
                          % gold)
    else:
        s -= 3
        notes_bad.append("修辞太少（%d 处），语言偏直白，可加一两处比喻"
                         % gold)
    sents = [x for x in re.split(r"[。！？]", essay) if len(x.strip()) > 2]
    if sents:
        avg = sum(len(x) for x in sents) / len(sents)
        if avg > 45:
            s -= 2
            notes_bad.append("句子平均 %.0f 字偏长，读着累，适当断句" % avg)
        elif avg < 10:
            s -= 1
            notes_bad.append("句子太碎，短句连发会显得急促")
        else:
            notes_good.append("长短句错落（平均 %.0f 字），节奏舒服" % avg)
    if len(essay) > 60 and "，" not in essay:
        s -= 1
        notes_bad.append("通篇没有逗号，读着喘不过气")
    scores["语言"] = round(max(0, s), 1)

    # 3) 情感：细节与情感词的密度
    s = 10.0
    det = sum(essay.count(m) for m in DETAIL_MARKS)
    emo = sum(essay.count(m) for m in EMO_MARKS)
    if det >= 3:
        notes_good.append("细节扎实（%d 处具体场景），情有所依" % det)
    else:
        s -= 3
        notes_bad.append("细节不足（%d 处），只喊口号不动人，"
                         "要用饭桌、路灯、深夜这些具体画面说话" % det)
    if emo >= 2:
        notes_good.append("情感真挚，有温度")
    else:
        s -= 2
        notes_bad.append("情感词偏少，内敛不等于冷冰冰")
    scores["情感"] = round(max(0, s), 1)

    # 4) 立意：结尾升华、点题
    s = 10.0
    if re.search(r"原来|才明白|懂得|长大|爱|怀念|愿|如今", tail):
        notes_good.append("结尾有升华，点到了情感内核")
    else:
        s -= 4
        notes_bad.append("结尾没有回扣主题，立意没收住")
    if "我" in essay:
        notes_good.append("有'我'的在场，第一人称的真情实感")
    else:
        s -= 2
        notes_bad.append("通篇没有'我'，缺了亲历感，像别人的故事")
    scores["立意"] = round(max(0, s), 1)

    # 5) 润色示范：缺修辞就送一句能直接抄的具体写法
    suggest = None
    theme = detect_theme(essay[:200])
    if theme and theme in BODY_BITS and gold < 3:
        unused = [b for b in BODY_BITS[theme] if b[:12] not in essay]
        if unused:
            suggest = ("可以挑一处'喊口号'的地方换成具体画面，比如："
                       "「%s」" % random.choice(unused))

    total = round(sum(scores.values()) / 4, 1)
    if dup:
        total = round(max(0, total - dup * 0.8), 1)
    lines = ["【作文点评】总分 %.1f/10" % total]
    lines.append("分项：" + "｜".join("%s %.1f" % (k, v)
                                     for k, v in scores.items()))
    if notes_good:
        lines.append("亮点：")
        lines += ["  ✔ " + g for g in notes_good[:4]]
    if notes_bad:
        lines.append("问题：")
        lines += ["  ✘ " + b for b in notes_bad[:4]]
    if suggest:
        lines.append("升格建议：")
        lines.append("  → " + suggest)
    lines.append("（全文 %d 字，%d 段）" % (words, len(paras)))
    return "\n".join(lines)


# ── 作文工作台存盘：重启竹也能接着改 ─────────────────
_STATE_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "记忆", "essay_state.json")


def save_state(st):
    """把作文工作台写盘（主题/标题/正文/修改轮数），下次开机接着改"""
    try:
        d = os.path.dirname(_STATE_PATH)
        if d:
            os.makedirs(d, exist_ok=True)
        with open(_STATE_PATH, "w", encoding="utf-8") as f:
            json.dump(st, f, ensure_ascii=False)
        return True
    except Exception:
        return False

def load_state():
    """开机时把上次的作文工作台捡回来"""
    try:
        with open(_STATE_PATH, "r", encoding="utf-8") as f:
            st = json.load(f)
        if isinstance(st, dict) and st.get("text") and st.get("theme"):
            st.setdefault("title", "")
            st.setdefault("turn", 0)
            return st
    except Exception:
        pass
    return None
