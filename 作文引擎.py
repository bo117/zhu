def _clean_token(tok):
    """洗掉引号、空白、尾巴语气词：'“父爱”'→'父爱'，
    '母亲都'→'母亲'，'母爱，再润色一下'→'母爱'"""
    if not tok:
        return ""
    tok = tok.strip().strip("“”\"'「」『』《》；;，。！？!? \u3000")
    tok = re.split(r"[，。！？!?,；;：:]+", tok)[0]
    tok = tok.strip("“”\"'「」『』 \u3000")
    tok = re.sub(r"^(都|全部|所有|一律|把|将|的|了)", "", tok)
    tok = re.sub(r"(都|全部|所有|一律|一下|了|的)$", "", tok)
    return tok


def parse_edit(cmd):
    """解析改文指令，返回 (旧词, 新词)；纯'改成XX'返回 ("", 新词)；
    没有明确指令返回 None"""
    for p in EDIT_PATTERNS:
        m = p.search(cmd)
        if m:
            if len(m.groups()) == 1:
                return "", _clean_token(m.group(1))
            return _clean_token(m.group(1)), _clean_token(m.group(2))
    return None


