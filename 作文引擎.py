# ── 写作主函数 ───────────────────────────────────────
def write_essay(theme, min_words=500, style="记叙文"):
    """写一篇作文，返回 (标题, 正文)。
    记叙文：开头 → 三个细节段（过渡+画面+升华）→ 点睛 → 结尾；
    议论文：论点 → 名言/事例论证 → 结尾呼吁。字数不足自动补细节段。"""
    rng = random.Random(random.random())   # 每次随机，重写必出新版
    if style == "议论文" and theme in ARGUMENTS:
        return _write_argument(theme, rng, min_words)
    return _write_narrative(theme, rng, min_words)


def _write_narrative(theme, rng, min_words):
    title = _pick(TITLES, theme, rng)
    opener = _pick(OPENERS, theme, rng)
    bits = list(BODY_BITS.get(theme, []))
    rng.shuffle(bits)
    depths = list(DEPTHS.get(theme, []))
    rng.shuffle(depths)
    trans = rng.sample(TRANSITIONS, k=min(len(TRANSITIONS), 6))
    parts = [opener]
    n_main = min(4 if min_words >= 600 else 3, len(bits))
    used_bits = bits[:n_main]
    ti, di = 0, 0
    for i, bit in enumerate(used_bits):
        para = bit
        if di < len(depths):
            para += depths[di]
            di += 1
        if i > 0 and ti < len(trans):
            para = trans[ti] + para
            ti += 1
        parts.append(para)
    parts.append(rng.choice(CLIMAX))   # 主体之后上点睛段
    parts.append(_pick(CLOSERS, theme, rng))
    essay = "\n\n".join(parts)

    # 字数不足：未用的细节 + 升华句搭伙成段补进去（一段两句，
    # 不碎片化）；细节用尽还差字，才把感受句缝进主体段尾巴
    rest_bits = list(bits[n_main:])
    rng.shuffle(rest_bits)
    while len(essay) < min_words and rest_bits:
        pair = [rest_bits.pop(0)]
        if di < len(depths):
            pair.append(depths[di])
            di += 1
        para = "".join(pair)
        if ti < len(trans):
            para = trans[ti] + para
            ti += 1
        parts.insert(-2, para)   # 插在点睛段前，保持"先叙事后点题"
        essay = "\n\n".join(parts)
    # 最后一招：感受句缝进主体段，每段最多补一句（不开新段）
    reflect = list(REFLECT)
    rng.shuffle(reflect)
    ri = 0
    n_body = max(1, len(parts) - 3)
    while len(essay) < min_words and ri < len(reflect):
        idx = 1 + (ri % n_body)
        if idx < len(parts) - 2:
            parts[idx] = parts[idx] + reflect[ri]
            ri += 1
            essay = "\n\n".join(parts)
        else:
            break
    return (title, essay)


def _write_argument(theme, rng, min_words):
    """议论文：论点 → 名言/事例（每段：连接语+素材+展开+分析+补强）→ 总结 → 呼吁。
    素材全上阵；字数不够就往论证段续句子，顺序每次打乱，篇篇不同。"""
    a = ARGUMENTS[theme]
    title = _pick(TITLES, theme, rng)
    parts = [rng.choice(a["thesis"])]
    quotes = a["quotes"][:]
    exams = a["examples"][:]
    rng.shuffle(quotes)
    rng.shuffle(exams)
    proofs = quotes + exams
    rng.shuffle(proofs)
    body = list(ARG_BODY)
    rng.shuffle(body)
    analysis = list(ANALYSIS)
    rng.shuffle(analysis)
    fills = list(ARG_FILL)
    rng.shuffle(fills)
    bi = ai = fi = 0
    for i, p in enumerate(proofs):
        para = "%s，%s" % (CONNECTS[i % len(CONNECTS)], p)
        if bi < len(body):
            para += body[bi]
            bi += 1
        if ai < len(analysis):
            para += analysis[ai]
            ai += 1
        if fi < len(fills):
            para += fills[fi]
            fi += 1
        parts.append(para)
    n_proofs = len(proofs)
    if ai < len(analysis):
        parts.append(analysis[ai])
        ai += 1
    else:
        parts.append(rng.choice(fills))
    parts.append(rng.choice(a["closes"]))
    SEP = chr(10) + chr(10)
    essay = SEP.join(parts)
    extra = body[bi:] + analysis[ai:] + fills[fi:]
    rng.shuffle(extra)
    n = 0
    while len(essay) < min_words and extra:
        idx = 1 + (n % n_proofs)
        parts[idx] = parts[idx] + extra.pop(0)
        n += 1
        essay = SEP.join(parts)
    return (title, essay)

