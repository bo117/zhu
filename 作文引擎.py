def canonical(word):
    """把口语说法归口到标准主题名（改文指令里"父亲→母亲"
    要能对上"父爱↔母爱"的联动表）"""
    return ALIAS.get(word, word)


def detect_theme(text):
    """从指令/文本里识别作文主题：别名优先，长词优先"""
    if not text:
        return None
    for alias in ALIAS:
        if alias in text:
            return ALIAS[alias]
    for t in sorted(THEMES, key=len, reverse=True):
        if t in text:
            return t
    return None


