def edit_essay(essay, old, new):
    """精准改文：主题级替换走联动表（父爱→母爱连人称一起换），
    普通替换只动指定词；长词/短语优先，避免拆坏。返回改动处数。"""
    if not old or not new or old == new:
        return essay, 0
    swaps = {}
    key = (canonical(old), canonical(new))
    if key in THEME_SWAP:
        swaps.update(THEME_SWAP[key])
    swaps.setdefault(old, new)
    count = 0
    for k in sorted(swaps, key=len, reverse=True):
        if not k:
            continue
        if k.startswith("__re__"):
            pat = k[6:]
            essay, n = re.subn(pat, swaps[k], essay)
            count += n
        elif k in essay:
            count += essay.count(k)
            essay = essay.replace(k, swaps[k])
    return essay, count


