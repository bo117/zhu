# ══════════════════════════════════════════════════════════════════
#  改稿通道（2026-09-21 新增）—— 「二次改善能力」
#  与 api_write_essay 的根本区别：那个是**从零写**，这个是**在已有稿子上动刀**。
#  核心约束：只改被指出的地方，其余原样保留；输出带【改】标记便于核对。
#  配套：训练.py --edit-aware（改动区加权损失）教模型「改动是有位置的」。
# ══════════════════════════════════════════════════════════════════
_REVISE_SYSTEM = (
    "你是「竹」，一个会改稿的写作助手。你的原则是："
    "只动被指出的地方，其余一字不改。改完要让人一眼看出你改了什么。")

_REVISE_PROMPT = """下面是一篇已经写好的作文，以及读者提出的意见。

【原作文】
{original}

【意见】
{feedback}

请按意见修改这篇作文，严格遵守：
1. 只改意见指出的问题，**其他段落原样保留**，不要重写全文；
2. 保持原来的主题、人称、事件，**总字数与原稿相差不超过 10%**（实测：不写这条它会扩写 48%）；
3. 你改动过的句子，用 【改】…【/改】 包起来，方便核对（没改的不加标记）；
4. 如果意见里提到的东西和原文对不上（比如意见说"换成笔袋"，但换掉的那个物件
   承担着"发光"这类功能，笔袋做不到），**按合理的方案处理并在改动处体现**，
   不要机械照搬。

直接输出修改后的全文，不要任何解释、不要重复意见。
"""


def _revise_prompt(original, feedback, brief=None):
    extra = ""
    if brief:
        th = (brief.get("theme") or "").strip()
        wd = brief.get("words")
        if th or wd:
            extra = "\n（这篇的主题是「%s」，%s字左右，请保持。）" % (
                th or "原主题", wd or "原")
    return (_REVISE_PROMPT.replace("{original}", (original or "").strip())
            .replace("{feedback}", (feedback or "").strip()) + extra)


def parse_marks(text):
    """把输出拆成 [(句子, 是否改动), ...]，并返回纯文本（去标记）。

    用途：①界面里把改动句高亮 ②评估时算「改动精准度 / 未涉及部分保留率」"""
    import re
    t = text or ""
    parts = []
    pos = 0
    for m in re.finditer(r"【改】(.*?)【/改】", t, re.S):
        if m.start() > pos:
            parts.append((t[pos:m.start()], False))
        parts.append((m.group(1), True))
        pos = m.end()
    if pos < len(t):
        parts.append((t[pos:], False))
    plain = "".join(p for p, _ in parts)
    return parts, plain


def api_revise_essay(original, feedback, brief=None, temperature=0.85):
    """按意见修改已写好的作文。成功返回 (改稿文本, 纯文本, 改动句数)，失败 None。

    ★ 走 _api_chat（本地模型优先，云端兜底）——和写作文同一条链路。
    ★ 输出保留【改】标记：既是给用户的「改动清单」，也是训练时的监督信号。"""
    if not USE_API_WRITER:
        return None
    if not (original or "").strip() or not (feedback or "").strip():
        _LAST_API_ERR[0] = "改稿需要原文和意见两样东西"
        return None
    prompt = _revise_prompt(original, feedback, brief)
    out = _api_chat(_REVISE_SYSTEM, prompt, 2400, temperature)
    if not out:
        return None
    parts, plain = parse_marks(out)
    n_changed = sum(1 for _, ch in parts if ch)
    return out, plain, n_changed


def find_essay_issues(text, temperature=0.6):
    """任务A（找问题）：给一篇作文，列出它的问题点。成功返回列表，失败 None。"""
    if not USE_API_WRITER:
        return None
    prompt = ("下面是学生写的一篇作文。请指出 3~5 个具体问题，"
              "每条要落到具体句子（引原文），说清「哪儿不好、该往哪改」。"
              "每行一条，用「· 」开头，不要空话、不要客套。\n\n" + (text or ""))
    out = _api_chat("你是严苛的中文作文老师。", prompt, 700, temperature)
    if not out:
        return None
    lines = [l.strip().lstrip("·-•0123456789.、 ") for l in out.splitlines()]
    return [l for l in lines if len(l) > 6][:6]


def api_revise_until_clean(original, feedback, brief=None, max_rounds=3,
                           on_round=None):
    """迭代改稿：改一轮 → **核对最初的意见还差哪条** → 带着未解决的再改。

    ★ 终止判据是「原意见是否逐条解决」，不是「文章是否完美」——
      实测发现后者永不为真（复检每轮都能挑出更细的新毛病：生造词、流水账、基调不符…）。
      那些新发现仍有价值：作为「额外发现」随结果一起报告出来。

    参数：on_round(轮号, 带标记文本, 纯文本, 未解决的原意见, 额外发现) 回调
    返回：(最终纯文本, 带标记文本, 总改动句数, 每轮未解决数, 额外发现列表)
    """
    cur = (original or "").strip()
    orig_fb = (feedback or "").strip()
    total_changed = 0
    best_plain, best_marked = cur, cur
    left_log, extra_found = [], []
    for r in range(1, max_rounds + 1):
        ask = orig_fb if r == 1 else (
            "还没改到位的意见（其余已改好，保持原样别动）：\n"
            + "\n".join("· " + x for x in left_log[-1]))
        res = api_revise_essay(cur, ask, brief)
        if not res:
            break
        marked, plain, n = res
        total_changed += n
        best_plain, best_marked = plain, marked
        # ① 判据：最初的意见还剩哪几条没解决
        left = _check_resolved(orig_fb, plain)
        left_log.append(left)
        # ② 复检：只作为「额外发现」报告，不参与终止
        extra = find_essay_issues(plain) or []
        extra_found = extra
        if on_round:
            try:
                on_round(r, marked, plain, left, extra)
            except Exception:
                pass
        if not left:
            break
        cur = plain
    return best_plain, best_marked, total_changed, left_log, extra_found

def _check_resolved(feedback, revised):
    """逐条核对：**最初的意见**里哪些还没解决。返回未解决的条目（空 = 全解决）。

    ★ 为什么需要它：实测发现「复检没问题」这个条件永不为真 ——
      任何文章都能挑出新毛病（而且新毛病更细）。终止判据必须是
      「原意见是否逐条解决」，而不是「文章是否完美」。"""
    if not feedback or not revised:
        return []
    prompt = ("下面是读者提出的意见，以及修改后的作文。\n"
              "请**逐条**核对：意见里的每一条，在改稿里是不是真的解决了？\n\n"
              "只列出**还没解决**的条目（照抄原意见的原文，每行一条）；\n"
              "如果全部都解决了，就只输出四个字：全部解决\n\n"
              "【意见】\n%s\n\n【改稿】\n%s"
              % (feedback[:900], revised[:2600]))
    out = _api_chat("你是严格的审稿人，只认真核对，不通融。", prompt, 600, 0.2)
    if not out:
        return []
    if "全部解决" in out:
        return []
    items = []
    for line in out.splitlines():
        t = line.strip().lstrip("·-•0123456789.、* ")
        if len(t) > 5 and "全部解决" not in t:
            items.append(t)
    return items[:6]


# ── 意见分流（2026-09-21）────────────────────────────────────────
# 用户的真实工作流里有两类反馈，处理方式必须不同：
#   局部类（"这句太书面""换个词"）→ 只改该改处，其他一字不动
#   结构类（"开头不行""结构乱，重新走"）→ 保留素材、重走结构
# 搞混的后果就是"改完不符合预期"。
_STRUCT_SYSTEM = ("你是「竹」，会重写结构的写作助手。"
                  "原则：素材一个不丢，结构按意见重走。")

_STRUCT_PROMPT = """下面是一篇作文，以及读者的意见 —— 读者认为它的**结构/开头**有问题。

【原作文】
{original}

【意见】
{feedback}

请**重走结构**，严格遵守：
1. **保留原文里的人物、事件、关键细节**（素材一个都不能丢，别变成另一篇）；
2. 重新安排开头方式、段落顺序、详略轻重；
3. 总字数与原稿相差不超过 10%；
4. 这条意见里指出的问题必须解决。
直接输出重写后的全文，不要解释、不要列提纲。
"""


def _classify_feedback(feedback):
    """判断意见属于哪种：'local'（局部改）或 'structure'（结构重走）。

    ★ 宁可判成 local —— 结构重走代价大（等于重写），误判会毁掉用户满意的地方。
    所以判据偏保守：只有明确指向结构/开头/顺序/脉络的才走 structure。"""
    fb = (feedback or "").strip()
    if not fb:
        return "local"
    import re as _re
    STRUCT_WORDS = ("结构", "顺序", "脉络", "重新写", "重写", "重来", "重新走",
                    "整篇", "通篇", "开头就", "开头不", "开头太", "起头",
                    "流水账", "太散", "串不起来", "节奏", "详略", "布局")
    if any(w in fb for w in STRUCT_WORDS):
        return "structure"
    # 文字信号不明显时，交给模型判一次（便宜且准）
    prompt = ("下面是一条对作文的意见。判断它要求的是：\n"
              "A 局部修改（改某些句子/用词/细节，整体结构不动）\n"
              "B 结构重走（开头、结构、顺序、脉络有问题，需要重新组织）\n\n"
              "只回答一个字母 A 或 B。\n\n意见：\n" + fb[:600])
    out = _api_chat("你是写作辅导老师，只做分类。", prompt, 8, 0.0)
    if out and out.strip().upper().startswith("B"):
        # 模型说是结构，但若意见里提到具体句子，仍需谨慎 → 认为局部
        if _re.search(r"这句|这句话|这个词|这个字|改成|换成", fb):
            return "local"
        return "structure"
    return "local"


def api_rewrite_structure(original, feedback, brief=None, temperature=0.85):
    """结构重走：保留素材，按意见重新组织全篇。成功返回 (新稿, 改动句数)。"""
    if not USE_API_WRITER:
        return None
    if not (original or "").strip() or not (feedback or "").strip():
        _LAST_API_ERR[0] = "重走结构需要原文和意见"
        return None
    prompt = (_STRUCT_PROMPT.replace("{original}", original.strip())
              .replace("{feedback}", feedback.strip()))
    out = _api_chat(_STRUCT_SYSTEM, prompt, int(len(original) * 2.2) + 400,
                    temperature)
    if not out:
        return None
    return out.strip(), -1        # -1 = 结构级重写（不是「改动句数」的概念）


def api_revise(original, feedback, brief=None, mode="auto"):
    """**统一改稿入口**（推荐用这个，而不是直接调 api_revise_essay）。

    mode: "auto"（默认，自动判断）/ "local" / "structure"
    返回 dict：{"mode", "text", "marked", "changed", "why"}
    """
    m = mode
    why = ""
    if m == "auto":
        m = _classify_feedback(feedback)
        why = "意见指向结构/开头/顺序 → 重走结构" if m == "structure" \
            else "意见指向局部问题 → 只改该改处"
    if m == "structure":
        r = api_rewrite_structure(original, feedback, brief)
        if not r:
            return None
        text, _ = r
        return {"mode": "structure", "text": text, "marked": text,
                "changed": -1, "why": why}
    r = api_revise_essay(original, feedback, brief)
    if not r:
        return None
    marked, plain, n = r
    return {"mode": "local", "text": plain, "marked": marked,
            "changed": n, "why": why}
