# 轮换记忆：让连续生成的作文避开最近用过的句子
# ★ 必须用「有序列表 + 全局单调时钟」，不能用 set ——
#   set 无序，「丢掉最旧的 k 个」根本做不到（旧版 list(rec)[:len-k]
#   丢的是哈希序前几个，不是时间序前几个 → 折返期形同虚设。
#   这就是金句被抽 47 次的根因：窗口记不住「最近」。
_RECENT = {}
_CLOCK = [0]          # 全局单调计数器：每 pick 一次 +1
# 冷却用的「剥物件名」正则：把台灯/围巾/钢笔 这类实词替成 ∅，
# 让同一句模板换了物件也能被认成「同一句」而被冷却。
_ESSAY_OBJ_RE = re.compile(
    r'台灯|围巾|钢笔|闹钟|相框|水杯|手电|布娃娃|存钱罐|发夹|橡皮|铅笔盒|'
    r'饭盒|手表|钥匙|雨伞|镜子|木凳|板凳|缝纫机|收音机|磁带|玻璃瓶|'
    r'铁盒|木盒|木箱|书包|球鞋|棉鞋|凉鞋|拖鞋|围巾|围裙|手套|')

# 套话黑名单：这些句式在成文中禁用（防模板化）
BANNED_PATTERNS = ['这件事让我明白', '这件事让我懂得', '我明白了一个道理',
                   '这让我想起了', '从此我改变', '原来这一切都是',
                   '生活是最好的老师', '成长的道路上', '在人生的道路上',
                   '那一刻我长大了', '我终于明白', '这不禁让我想起',
                   '岁月的长河', '时光的车轮', '记忆的长河']


def _clean_pool(pool):
    """滤掉含套话的句子"""
    out = []
    for p in pool:
        if any(b in p for b in BANNED_PATTERNS):
            continue
        out.append(p)
    return out if out else list(pool)


def _global_fresh(seq, rng, key, k=None):
    """跨篇冷却：把最近用过的句子排到队尾，优先给「久没露脸」的。

    ★ 这是治「复读机」的主力，与 pick_fresh 同机制但用于**已格式化的成句**
      （pick_fresh 用于还没填 {obj} 的裸模板）。
    ★ 冷却窗 k：默认取池子的 1/2（记忆类句子复用价值高，但必须轮换），
      池子只有几条时自然退化为轮换。
    ★★ 踩过的坑：早版按传入字符串记冷却，但传进来的句子里 {obj} 已被替换成
      「围巾」「台灯」……**每篇的成句字面都不同** → 冷却键对不上，等于没记，
      实测最高单句频次纹丝不动（40 次）。
      正确做法：冷却按**归一化后的成句**（去物件名）记，即剥掉「围巾」这类实词，
      只留句子骨架 ——「{obj}不出声。可家里很多话…」才是真正要轮换的单位。
    """
    seq = [x for x in seq if x]
    if not seq:
        return seq
    # 冷却键：剥掉具体物件名后的骨架
    skel = lambda s: _norm(_ESSAY_OBJ_RE.sub("∅", s))
    if k is None:
        k = max(2, len(seq) // 2)
    q = _RECENT.setdefault("_g:" + key, [])
    _CLOCK[0] += 1
    cutoff = _CLOCK[0] - k
    hot = set(skel(p) for p, ts in q if ts > cutoff)
    cold = [x for x in seq if skel(x) not in hot]
    out = cold if cold else list(seq)
    rng.shuffle(out)
    for p in out:
        sp = skel(p)
        q[:] = [(a, t) for a, t in q if skel(a) != sp]
        q.append((p, _CLOCK[0]))
    cap = max(128, k * 4)
    if len(q) > cap:
        del q[:len(q) - cap]
    return out


def pick_fresh(pool, rng, key, k=8):
    """从池子里挑一句最近没用过的；池子小就轮着来。

    ★ 冷却窗口 k 的意义：一句被用过后，接下来 k 次抽取都跳过它。
      池子越大越该放大 k（否则刚用过的立刻又被抽中）。
      ★ 自动调窗：k 小于池子的 1/4 时按池子比例抬到 1/4 ——
        池子 50 条、k=8 的话，一句每6 篇就能被抽回一次（实测最高 47/120 篇）。
    """
    pool = [p for p in pool if p]
    if not pool:
        return ""
    k = max(k, len(pool) // 4)
    q = _RECENT.setdefault(key, [])
    _CLOCK[0] += 1
    cutoff = _CLOCK[0] - k
    # 热区 = 最近 k 次被选中的条目（按时间戳判定，天然有序）
    hot = set(p for p, ts in q if ts > cutoff)
    cold = [p for p in pool if p not in hot]
    pick = rng.choice(cold if cold else pool)
    # 记住这次选择：同一句只保留最新时间戳
    q[:] = [(p, ts) for p, ts in q if p != pick]
    q.append((pick, _CLOCK[0]))
    cap = max(64, k * 4)
    if len(q) > cap:
        del q[:len(q) - cap]
    return pick


