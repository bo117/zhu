def _quality_score(text, target_words=0, theme=""):
    """给一段作文打分（分越高越好）。纯规则，快、稳、不花钱。

    四个维度：
      · 复读   —— 句级重复率，扣分
      · 套话   —— 命中陈词滥调，每个扣分
      · 细节   —— 具体量词/动作词的密度，加分（治「模板化」的核心指标）
      · 长度   —— 离目标字数太远扣分
    """
    report = quality_report(text, target_words, theme)
    return report["score"] if len((text or "").strip()) >= 60 else -999.0


def _pick_best(cands, target_words=0, theme=""):
    """从候选里挑分最高的；并列时取先出现的（温度递增，先出现的通常更稳）"""
    best, best_s = None, None
    for c in cands:
        if not c:
            continue
        s = _quality_score(c, target_words, theme)
        if best_s is None or s > best_s:
            best, best_s = c, s
    return best, best_s


