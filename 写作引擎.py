# ---- 原创闸门：与范文语料的重合率超过 30% 就不允许交付 ----
_CORPUS_SEN = None
_PUNCT = re.compile('[' + '\u3002\uff01\uff1f\uff1b\uff1a\u3001'
                   + '\u201c\u201d\u2018\u2019\uff08\uff09\u300a\u300b'
                   + ' \t\r\n\u2026\u2014,.;:!?]')
_SPLIT = re.compile('[' + '\u3002\uff01\uff1f' + '\n]')


def _norm(s):
    return _PUNCT.sub('', s)


def _corpus_sentences():
    """范文语料的全部句子（规范化后），第一次用时加载并缓存"""
    global _CORPUS_SEN
    if _CORPUS_SEN is not None:
        return _CORPUS_SEN
    import glob
    sents = set()
    for fp in glob.glob(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                     '作文范文_qa.jsonl')):
        try:
            with open(fp, encoding='utf-8') as f:
                for line in f:
                    try:
                        body = json.loads(line).get('output', '')
                    except Exception:
                        continue
                    for s in _SPLIT.split(body):
                        ns = _norm(s)
                        if len(ns) >= 10:
                            sents.add(ns)
        except Exception:
            pass
    _CORPUS_SEN = sents
    return sents


# 句式层模糊比对的倒排索引（3-gram → 范文句序号），惰性构建
_CORPUS_INDEX = None
_CORPUS_LIST = None


def _grams(s, n=3):
    """去标点后的字符 n-gram（句式层比对用）"""
    s = _norm(s)
    return [s[i:i + n] for i in range(max(0, len(s) - n + 1))]


def _corpus_index():
    """把范文语料建成 3-gram 倒排索引，供 overlap_check 做句式层模糊比对。
    返回 (句子列表, 倒排索引)。与 _corpus_sentences 同源，但保留列表以算 Jaccard。"""
    global _CORPUS_INDEX, _CORPUS_LIST
    if _CORPUS_INDEX is not None:
        return _CORPUS_LIST, _CORPUS_INDEX
    sents = sorted(_corpus_sentences())
    idx = {}
    for i, s in enumerate(sents):
        for g in set(_grams(s, 3)):
            idx.setdefault(g, set()).add(i)
    _CORPUS_LIST, _CORPUS_INDEX = sents, idx
    return _CORPUS_LIST, _CORPUS_INDEX


def overlap_check(essay, limit=0.15, fuzzy=0.62):
    """复读闸门（新版，四层检测，专治旧版「恒真」的毛病）。

    旧版只做逐字精确匹配，而竹的句子是素材片段现场组装，几乎不可能与范文
    逐字相同 → 重合率恒为 0，闸门形同虚设，write_essay2 里「最多重写 3 次」
    成了死代码。新版分两组四层：
      A 篇内复读（无需外部参照，直击病灶）：
        ① 字句自重复 —— 同一句在文里出现 2 次以上
        ② 句式自重复 —— 两句 3-gram Jaccard ≥ fuzzy（换词共用骨架）
      B 与范文重合（防抄袭/防撞真题范文）：
        ③ 字句层 —— 与范文句逐字相同
        ④ 句式层 —— 与任一范文句 3-gram Jaccard ≥ fuzzy
    任一命中都算复读句；复读句占比 ≤ limit 才放行。返回 (是否合格, 复读率)。"""
    sens = [s for s in (_norm(x) for x in _SPLIT.split(essay))
            if len(s) >= 10]
    n = len(sens)
    if n == 0:
        return True, 0.0
    corpus = _corpus_sentences()
    bad = [False] * n
    gram_cache = [set(_grams(s, 3)) for s in sens]

    # A① 篇内字句自重复
    cnt = {}
    for s in sens:
        cnt[s] = cnt.get(s, 0) + 1
    for i, s in enumerate(sens):
        if cnt[s] > 1:
            bad[i] = True

    # A② 篇内句式自重复（换词共用骨架）
    for i in range(n):
        gi = gram_cache[i]
        if bad[i] or not gi:
            continue
        for j in range(i + 1, n):
            if bad[j]:
                continue
            gj = gram_cache[j]
            u = gi | gj
            if u and len(gi & gj) / len(u) >= fuzzy:
                bad[i] = bad[j] = True

    # B③ 与范文字句层重合
    for i, s in enumerate(sens):
        if s in corpus:
            bad[i] = True

    # B④ 与范文句式层模糊比对（换词共用骨架）
    clist, idx = _corpus_index()
    for i in range(n):
        if bad[i]:
            continue
        gs = gram_cache[i]
        if not gs:
            continue
        cands = set()
        for g in gs:
            m = idx.get(g)
            if m:
                cands |= m
        for ci in cands:
            cgs = set(_grams(clist[ci], 3))
            u = gs | cgs
            if u and len(gs & cgs) / len(u) >= fuzzy:
                bad[i] = True
                break

    ratio = sum(bad) / n
    return ratio <= limit, round(ratio, 3)


