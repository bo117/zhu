# 拼接方式：让两种槽位自然咬合，而不是硬拼
_JOINS = [
    "{A}，{B}",
    "{A}。{B}",
    "{A}——{B}",
    "{A}；{B}",
]


def _compose_line(obj, rng):
    """现场组装一句物件句：槽位A × 槽位B × 连接方式。"""
    a = rng.choice(_SLOT_A).format(obj=obj)
    b = rng.choice(_SLOT_B)
    return rng.choice(_JOINS).replace("{A}", a).replace("{B}", b)


