def _split_title(text, theme):
    """仅把首行识别为标题，正文里的书名号不能截掉前文。"""
    source = (text or "").strip()
    first, separator, remainder = source.partition("\n")
    title = re.fullmatch(r"(?:#+\s*)?《([^》]{1,60})》", first.strip())
    if title:
        return title.group(1), remainder.strip()
    if separator and 0 < len(first.strip()) <= 16 and not re.search(r"[。！？!?，,：:“”]", first):
        return first.strip(), remainder.strip()
    return theme or "作文", source


