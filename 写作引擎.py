def _kv(text, key):
    m = re.search(key + r"[:：]\s*(.+)", text or "")
    return m.group(1).strip() if m else ""


def _parse_chapters(text, start_no, n):
    """从文本里抠「序号. 章节名 | 剧情」行；按位置重新编号并补足 n 条"""
    out = []
    for ln in (text or "").split("\n"):
        m = re.match(r"\s*(\d+)\s*[.、:：]\s*(.+)", ln)
        if m:
            body = m.group(2).strip()
            parts = re.split(r"[|｜]", body, 1)
            out.append({"no": 0, "title": parts[0].strip()[:16],
                        "brief": parts[1].strip() if len(parts) > 1 else ""})
    for k, c in enumerate(out):
        c["no"] = start_no + k
    while len(out) < n:
        k = start_no + len(out)
        out.append({"no": k, "title": "第%d章" % k, "brief": "推进主线剧情"})
    return out[:n]


def _parse_novel_setting(text, n):
    """解析全书设定与首批大纲"""
    title = "未命名"
    m = re.search(r"《([^》]{1,40})》", text or "")
    if m:
        title = m.group(1).strip()
    chars = []
    for ln in (text or "").split("\n"):
        s = ln.strip()
        if s.startswith(("-", "·", "*")):
            parts = re.split(r"[，,、]", s.lstrip("-·* ").strip())
            if len(parts) >= 2:
                chars.append({"name": parts[0].strip()[:10],
                              "role": parts[1].strip()[:20],
                              "trait": parts[2].strip()[:20]
                              if len(parts) > 2 else ""})
    return {"title": title, "intro": _kv(text, "简介"),
            "world": _kv(text, "世界观"),
            "characters": chars[:10], "chapters": _parse_chapters(text, 1, n)}


