# 骨架形状随机化 —— 第二轮反模板化的主攻手（结构层，2026-09-16）
# ──────────────────────────────────────────────────────────────────────
# 折返期解决的是「结构组合不重复」，但段落形状（骨架）仍近乎固定：
#   开头段 → 主线段 → 经过段 →（70% 旁支段）→ 点睛段 → 收尾段，
#   段数集中在 6/7 两档、长短档高度雷同 —— 这就是体检里
#   「前 3 种骨架占 41.8%、`7|0011010` 一家独大」的直接原因。
# 这里在成文后、交付前，对正文段做「只动边界、不动句子」的随机整形：
#   合并 —— 相邻两个正文段并作一段（段数 −1，长段更突出）
#   拆分 —— 较长的正文段在句界处一分为二（段数 +1），两半都必须仍含主线锚点词
# 句子原样保留、不新增不重复，所以不会放大句级重复——这与已回退的
# 「段落节奏」（把补字数集中到某几段）是两码事：那次动的是句子分布，这次只动段落边界。
# 想关掉：SHAPE_SHAKE = False（A/B 体检用）。
# ══════════════════════════════════════════════════════════════════════
SHAPE_SHAKE = True            # 总开关
SHAKE_MERGE_P = 0.30          # 合并概率
SHAKE_SPLIT_P = 0.45          # 拆分概率（不与合并同篇发生）


def _shake_shape(parts, rng, core):
    """对正文段做随机整形，返回新的 parts 列表（不改传入列表）。
    core = 主线锚点词集合（铁则 2 算好的），拆分时保证两半都锚得住主线。"""
    if not SHAPE_SHAKE or rng is None:
        return parts
    if len(parts) < 5:
        return parts
    body = list(range(1, len(parts) - 1))     # 开头段与收尾段不参与
    if len(body) < 2:
        return parts
    roll = rng.random()
    if roll < SHAKE_MERGE_P:                  # ── 合并 ──
        i = rng.choice(body[:-1])
        return parts[:i] + [parts[i] + parts[i + 1]] + parts[i + 2:]
    if roll < SHAKE_MERGE_P + SHAKE_SPLIT_P:  # ── 拆分 ──
        cands = [i for i in body if len(parts[i]) >= 90]
        if not cands:
            return parts
        i = rng.choice(cands)
        sents = [s for s in re.split(r'(?<=[。！？])', parts[i]) if s.strip()]
        if len(sents) < 2:
            return parts
        order = list(range(1, len(sents)))
        rng.shuffle(order)
        for k in order:
            left, right = ''.join(sents[:k]), ''.join(sents[k:])
            if len(left) < 30 or len(right) < 30:
                continue
            if core and not (any(n in left for n in core)
                             and any(n in right for n in core)):
                continue
            return parts[:i] + [left, right] + parts[i + 1:]
    return parts                              # ── 不动（约 1/4 的篇）──


