_BEATS = ["开端", "发展", "发展", "高潮", "结局"]


def _beat_para(genre, beat, used, rng):
    """从题材节拍池里取一段没用过的料"""
    pool = (suc.GENRES.get(genre) or {}).get("节拍", {}).get(beat) or []
    fresh = [p for p in pool if (genre, beat, pool.index(p)) not in used]
    if fresh:
        p = rng.choice(fresh)
        used.add((genre, beat, pool.index(p)))
        return p
    return None


def _book_title(genre, rng):
    return "《%s》" % rng.choice(BOOK_TITLES.get(genre) or [genre + "故事"])


def parse_characters(text):
    """人物设定解析：每行"姓名，身份，性格"，解析成卡片"""
    cards = []
    for ln in (text or '').split('\n'):
        ln = ln.strip().strip('；;。')
        if not ln or len(ln) < 2:
            continue
        parts = re.split(r'[，,、:：]', ln)
        if len(parts) >= 2:
            cards.append({'name': parts[0].strip()[:8],
                          'role': parts[1].strip()[:16],
                          'trait': (parts[2].strip()[:20] if len(parts) > 2 else '')})
    return cards[:6]


def characters_block(cards):
    if not cards:
        return ''
    lines = ['【人物设定】']
    for c in cards:
        lines.append('  · %s（%s%s）' % (c.get('name', ''), c.get('role', ''),
                                         ('，' + c['trait']) if c.get('trait') else ''))
    return '\n'.join(lines)


def _rule_start_novel(brief):
    """【规则引擎】开新书：书名 + 第一章（开场段 + 开端节拍）"""
    rng = random.Random(random.random())
    genre = brief["genre"] or "青春校园"
    if genre not in suc.GENRES:          # 题材名不在库里 → 退回默认，别崩
        genre = "青春校园"
    ending = brief["ending"] or "圆满"
    g = suc.GENRES[genre]
    used = set()
    opener = rng.choice(g["开场"])
    used.add((genre, "开场", g["开场"].index(opener)))
    b = _beat_para(genre, "开端", used, rng)
    fill = list(NOVEL_FILL)
    rng.shuffle(fill)
    ch1 = opener + "\n\n" + (b or "") + "\n\n" + fill[0] + fill[1]
    state = {
        "mode": "novel",
        "theme": None,
        "genre": genre,
        "ending": ending,
        "technique": brief.get("technique"),
        "words": brief.get("words", 800),
        "title": _book_title(genre, rng),
        "text": ch1,
        "chapters": [{"no": 1, "title": rng.choice(suc.CHAPTER_TITLES["开端"]),
                      "text": ch1}],
        "used": sorted(used),
        "turn": 0,
        "style": "小说",
        "characters": parse_characters(brief.get("characters")),
    }
    return state


def _rule_continue_novel(state):
    """【规则引擎】续写下一章：按节拍推进；终章按结局收笔；终章后再续是番外"""
    rng = random.Random(random.random())
    genre = state["genre"]
    if genre not in suc.GENRES:
        genre = "青春校园"
    g = suc.GENRES[genre]
    used = set(tuple(u) for u in state.get("used", []))
    n = len(state["chapters"])          # 已写到第几章
    beat = _BEATS[n] if n < len(_BEATS) else "番外"
    fill = list(NOVEL_FILL)
    rng.shuffle(fill)
    if beat == "结局":
        text = rng.choice(suc.ENDINGS[state.get("ending", "圆满")]["novel"])
        ch_title = rng.choice(suc.CHAPTER_TITLES["结局"])
    elif beat == "番外":
        b = _beat_para(genre, "发展", used, rng)
        text = (b or "故事讲完了，可日子还在过。") + "\n\n" + \
            rng.choice(g["金句"]) + "\n\n" + "（番外一篇，全卷完。）"
        ch_title = "番外 · " + rng.choice(suc.CHAPTER_TITLES["发展"])
    else:
        b = _beat_para(genre, beat, used, rng)
        if not b:
            b = rng.choice(g["开场"])     # 节拍用尽 → 拿开场段顶上
        extra = []
        if n >= 2 and rng.random() < 0.6:
            extra.append(rng.choice(g["金句"]))
        text = b + "\n\n" + "\n\n".join(extra + [fill[0], fill[1]])
        ch_title = rng.choice(suc.CHAPTER_TITLES[beat])
    chapter = {"no": n + 1, "title": ch_title, "text": text}
    state["chapters"].append(chapter)
    state["text"] = "\n\n".join(
        ["第%s章 %s\n%s" % (_cn(c["no"]), c["title"], c["text"])
         for c in state["chapters"]])
    state["used"] = sorted(used)
    state["turn"] = state.get("turn", 0) + 1
    state["last_beat"] = beat
    return state, chapter


def _full_novel_text(st, author):
    """把 state 的章节拼成「书名+简介+人物+目录+正文」的整本书文本"""
    SEP = chr(10) + chr(10)
    genre = st.get("genre") or ""
    g = suc.GENRES.get(genre) or {}
    head_parts = [
        "%s" % str(st.get("title") or "未命名").strip("《》"),
        "体裁：%s小说 ｜ 作者：%s ｜ 结局走向：%s"
        % (genre, author, st.get("ending") or ""),
        "【内容简介】" + (st.get("intro") or g.get("简介") or ""),
    ]
    if st.get("world"):
        head_parts.append("【世界观】" + st["world"])
    cb = characters_block(st.get("characters") or [])
    if cb:
        head_parts.append(cb)
    head_parts.append("【目录】")
    head_parts.append(chr(10).join("  第%s章  %s" % (_cn(c["no"]), c["title"])
                                   for c in st["chapters"]))
    head = SEP.join(head_parts)
    body = SEP.join("第%s章 %s%s%s" % (_cn(c["no"]), c["title"], SEP, c["text"])
                    for c in st["chapters"])
    return head + SEP + SEP + body + SEP + SEP + "（全书完）"


def write_full_novel(brief):
    """整本小说：作者信息、简介、目录、正文一次成书。

    优先用 **API 长篇小说引擎**（章数按目标字数定，可写长篇）；
    无 key / 失败自动回退规则引擎（回退时章数也改为可配，不再死钉 5 章）。"""
    rng = random.Random(random.random())
    pen_names = ["竹下听风", "南巷旧人", "青梧", "一盏灯", "拾光者", "无名指"]
    author = rng.choice(pen_names)
    st = api_write_novel(brief)
    if st:
        st["author"] = author
        st["text"] = _full_novel_text(st, author)
        st["turn"] = 0
        return st
    # ---- 回退：规则引擎 ----
    n = max(5, _novel_chapter_count(brief))
    st = _rule_start_novel(brief)
    while len(st["chapters"]) < n:
        st, ch = _rule_continue_novel(st)
    st["author"] = author
    st["text"] = _full_novel_text(st, author)
    st["turn"] = 0
    return st


def start_novel(brief):
    """开新书：优先 API（设定+大纲+前 2 章），失败回退规则引擎。

    长篇《龙族》那类作品靠的是「先大纲、再逐章、每章带前情提要」，
    后面用 continue_novel 一章章接着写就能持续产出。"""
    st = api_write_novel(brief, chapters=2)
    if st:
        return st
    return _rule_start_novel(brief)


def continue_novel(state):
    """续写下一章：API 小说优先（带前情提要、可持续产出）；失败/非 API 小说回退规则引擎。"""
    if state.get("by") == "api" and state.get("mode") == "novel":
        ext = api_extend_novel(state, 1)
        if ext:
            return ext
    return _rule_continue_novel(state)


def _cn(n):
    digits = "零一二三四五六七八九十"
    if n < 10:
        return digits[n]
    if n == 10:
        return "十"
    if n < 20:
        return "十" + digits[n % 10]
    return str(n)


