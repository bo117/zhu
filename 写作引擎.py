# 根因就在下面这三个默认值：opening 缺省「开门见山」、structure 缺省
# 「总分总」、technique 缺省 None —— 用户不指定，就永远长成同一个骨架。
#
# 改法：把「开头×结构×技法×深度」当成一个「结构字胚」，给它加冷却。
#   显式指定的要素 → 一律尊重，不动。
#   未指定的要素   → 从组合空间抽，且最近 STRUCT_COOLDOWN 篇内不重复。
# 想完全回到旧行为：把 STRUCT_ROTATE 改成 False。
# ══════════════════════════════════════════════════════════════════════
STRUCT_ROTATE = True          # 总开关
STRUCT_COOLDOWN = 25          # 最近多少篇内不允许重复同一个结构组合
                              # （第二轮 15→25：冷却窗口越长，连续作文越难踩同一个组合）
_STRUCT_HIST = []             # 滑动的结构签名历史

# 【已回退】曾试过「段落节奏」（把补字数集中到某几段，用来打散长度分布）。
# A/B 实测有害：骨架种类确实从 17 涨到 39、前3集中度 55.5%→27.5%，
# 但**篇间相似度从 0.286 恶化到 0.416**，≥0.3 的文章对从 39% 飙到 88%。
# 原因：把句子灌进同一段，反而放大了模板句的重复；且出现「一段极长、其余极短」的畸形。
# 结论：长度形状不该在「补字数」这一层做。保持 A/B 已验证有效的版本。


def _struct_sig(b):
    return (b.get("opening"), b.get("structure"),
            b.get("technique"), b.get("depth"))


def _struct_push(sig):
    _STRUCT_HIST.append(sig)
    while len(_STRUCT_HIST) > STRUCT_COOLDOWN:
        _STRUCT_HIST.pop(0)


def rotate_structure(brief, rng=None):
    """结构折返期：未显式指定的结构要素，抽一个近期没出现过的组合。"""
    if not STRUCT_ROTATE:
        return brief
    if rng is None:
        rng = random
    ex = brief.get("_explicit") or {}
    b = dict(brief)
    if _struct_sig(b) not in _STRUCT_HIST:
        _struct_push(_struct_sig(b))
        return b
    for _ in range(40):                      # 撞车了重抽，最多试 40 次
        if not ex.get("opening"):
            b["opening"] = rng.choice(OPENINGS)
        if not ex.get("structure"):
            b["structure"] = rng.choice(STRUCTURES)
        if not ex.get("technique"):
            b["technique"] = rng.choice([None] + list(TECHNIQUES))
        if not ex.get("depth"):
            b["depth"] = rng.choice(["快速", "标准", "深度"])
        sig = _struct_sig(b)
        if sig not in _STRUCT_HIST:
            _struct_push(sig)
            return b
    _struct_push(_struct_sig(b))             # 实在抽不出来，接受重复
    return b


def structure_stats():
    """看折返期状态（体检/调试用）"""
    return {"enabled": STRUCT_ROTATE, "cooldown": STRUCT_COOLDOWN,
            "hist_len": len(_STRUCT_HIST), "recent": list(_STRUCT_HIST[-5:])}


