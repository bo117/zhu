    lines = text.split("\n")
    title, body = "", text
    first = lines[0].strip()
    if len(lines) > 1 and 0 < len(first) <= 20:
        title = first.strip("《》").strip()
        body = "\n".join(lines[1:]).strip()
    theme = detect_theme2(body) or detect_theme2(title) or "成长"
    st = {
        "mode": "essay",
        "imported": True,
        "theme": theme,
        "title": title or ("无题·%s" % theme),
        "text": body,
        "turn": 0,
        "style": "记叙文",
        "words": len(body),
        "ending": None,
        "opening": "开门见山",
        "structure": None,
        "master": None,
        "depth": "标准",
    }
    return st


