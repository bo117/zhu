    name = (name or '').strip().strip('《》')
    d = load_directions()
    if name in d:
        d.pop(name)
        save_directions(d)
        return True, '自定义方向「%s」已删除' % name
    return False, '内置方向不能删，自定义方向里没找到「%s」' % name


