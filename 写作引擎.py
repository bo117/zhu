def _mine_obj(text, rng, theme=""):
    """★ 从任意文本里**挖**出可作锚点的物件（治「表外主题」的关键）。
       这是「不绑死」的保证：THEME_OBJS 只覆盖几十个常见主题，
       剩下的主题一律靠这里现挖 —— 挖到什么用什么，不卡死、不瞎配。

       实测踩过的坑（都修了）：
       · 「外卖」被 jieba 标成动词 v（因为也有「点外卖」的意思）→ 放宽到 nv
       · 「猫」只有 1 字，撞了 len>=2 门槛 → 放宽到 1~4 字
       · 「期末考试」整体是一个 n，短词「期末」不该顶替它 → 保留最长候选
    """
    if not text:
        return None
    try:
        import jieba.posseg as pseg
        # flag 以 n/v 开头的都算「可能是物件」——外卖被判 v 是常态，
        # 宁可放过（后面还有过滤器），也不能因为词性误判就把主题丢了。
        cands = [w.word for w in pseg.cut(text)
                 if w.flag[0] in ("n", "v", "t")
                 and 1 <= len(w.word) <= 4
                 and not re.search(r"[的了着过是为]", w.word)]
    except Exception:
        cands = re.findall(r"[一-龥]{1,4}", text)

    # 抽象词/虚词过滤 —— 这类不能当物件锚点
    bad = set(
        "时间 事情 东西 地方 样子 办法 时候 感觉 世界 生活 人生 一点 一些 "
        "问题 关系 目标 精神 意义 价值 态度 心情 原因 结果 阶段 过程 方面 "
        "同学 老师 朋友 父母 母亲 父亲 人们 自己 别人 大家 人家 我们 他们 "
        "以及 但是 因为 所以 如果 虽然 就是 还是 已经 曾经 正在 一直 "
        "多少 这个 那个 这些 那些 这样 那样 一样 起来 下来 过去 后来 "
        "开始 结束 继续 变成 成为 感到 觉得 希望 觉得 知道 明白 理解"
        .split())
    cands = [c for c in cands if c not in bad]
    if not cands:
        return None

    # 去掉被别的候选包含的短词（桂花树 vs 桂花 → 留桂花树）
    uniq = [c for c in cands
            if not any(c != o and c in o for o in cands)]
    # 最长的优先：具象名词通常就是最完整的那个（期末考试 > 期末）
    uniq.sort(key=lambda s: -len(s))
    top = [c for c in uniq if len(c) >= len(uniq[0])]
    return rng.choice(top)


def _theme_obj(theme, main_bit, rng):
    """★ 按主题选物件（治脱节）。四级兜底，**任何一级都不返回随机白名单**：
       ① 主题命中 THEME_OBJS → 从该主题的物件里挑（主线上已出现的优先）
       ② 主题模糊匹配（母亲/老师这类同义写法）
       ③ **从主线上挖具象名词** —— 表外主题（如「期末考试」）走这条，
          挖到什么用什么，至少和情节一致
       ④ 主题本身就是具象物（用户直接说「蜡烛」）→ 直接用它
       ⑤ 实在挖不出才退回通用白名单（此时已经无从推断，别硬凑）
    """
    theme = (theme or "").strip()
    mb = main_bit or ""

    for key in (theme, theme[:2], theme[-2:]):
        if key in THEME_OBJS:
            pool = THEME_OBJS[key]
            hit = [o for o in pool if o in mb]
            return rng.choice(hit if hit else pool)
    for key, pool in THEME_OBJS.items():
        if key and key in theme:
            hit = [o for o in pool if o in mb]
