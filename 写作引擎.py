def detect_ending(text):
    """结局识别：优先认「结局/结尾/收尾」上下文里的词，防止
    「写一篇关于遗憾的作文」里的主题词被错当成结局"""
    if not text:
        return None
    m = re.search(r"(好|坏|大团圆|圆满|开放|遗憾|虐心|治愈)?结局", text)
    if m and m.group(0):
        e = suc.ENDING_ALIAS.get(m.group(0))
        if e:
            return e
    if not _ENDING_HINT_RE.search(text):
        return None
    for a, e in sorted(suc.ENDING_ALIAS.items(), key=lambda kv: -len(kv[0])):
        if a in text:
            return e
    return None


