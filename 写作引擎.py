def direction_add(name, samples_text):
    name = (name or '').strip().strip('《》')
    if not name or len(name) > 20:
        return False, '题目要 1~20 个字'
    sents = [s.strip() for s in re.split(r'[。！？\n]', samples_text or '')
             if 25 <= len(s.strip()) <= 150]
