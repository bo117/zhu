def _pick_context_obj(rng, *texts):
    """只从当前故事已经出现的句子里选物件，禁止凭空引入无关物件。"""
    context = "".join(text or "" for text in texts)
    found = [obj for obj in _SAFE_OBJ if obj in context]
    return rng.choice(found) if found else None


