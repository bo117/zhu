def detect_theme2(text):
    """65 主题识别：核心 19 个听作文引擎的，其余听素材库的
    ★ 2026-10-14 新增第四级「自由提取」：
      白名单覆盖不了的词（外卖/猫/蜡烛/航天…）原先一律返回 None，
      导致下游拿不到主题 → 只能退回随机白名单物件 → 满篇不相干。
      现在用「关于X的 / 写X / X的」句式把 X 抠出来当主题，
      **主题池从此不设上限**（这是用户明确要求的：别绑死）。
    """
    if not text:
        return None
    t = base.detect_theme(text)
    if t:
        return t
    for a, theme in _EXTRA_THEME_ALIAS.items():
        if a in text:
            return theme
    for th in sorted(suc.ALL_THEMES, key=len, reverse=True):
        if th in text:
            return th

    # ── 第四级：自由提取（不限主题池）──
    # 句式优先：「关于X的」「写X」「一篇X」「X的作文」，抓 1~6 字
    for pat in (r"关于\s*([\u4e00-\u9fff]{1,6}?)\s*的",
                r"写(?:一篇|篇|一篇关于)?\s*([\u4e00-\u9fff]{1,6}?)\s*(?:作文|文章|散文|随笔)",
                r"([\u4e00-\u9fff]{2,6}?)\s*的\s*(?:作文|文章|散文|随笔)",
                r"(?:讲|说|写)\s*(?:一下|讲讲|说说)?\s*([\u4e00-\u9fff]{2,6})"):
        m = re.search(pat, text)
        if m:
            got = m.group(1).strip()
            # 去掉黏在后面的体裁/结构词（「母爱记叙文」→「母爱」）
            got = re.split(r"[的了]", got)[0]
            got = re.sub(r"(?:记叙|议论|抒情|说明|散文|写景|叙事)$", "", got)
            got = re.sub(r"(?:作文|文章|随笔|演讲稿|读后感)$", "", got)
            if 1 <= len(got) <= 6:
                return got
    return None


