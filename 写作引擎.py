def _xml_esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _write_docx(path, blocks):
    """纯标准库写 docx（Word 直接打开）。
    blocks = [(样式, 文本)]，样式取 title/meta/head/body/tail"""
    import zipfile
    paras = []
    for kind, txt in blocks:
        t = _xml_esc(txt.replace("\n", " "))
        if kind == "title":
            paras.append(
                '<w:p><w:pPr><w:jc w:val="center"/></w:pPr>'
                '<w:r><w:rPr><w:b/><w:sz w:val="36"/></w:rPr>'
                '<w:t xml:space="preserve">%s</w:t></w:r></w:p>' % t)
        elif kind == "head":
            paras.append(
                '<w:p><w:r><w:rPr><w:b/></w:rPr>'
                '<w:t xml:space="preserve">%s</w:t></w:r></w:p>' % t)
        else:
            paras.append(
                '<w:p><w:r><w:t xml:space="preserve">%s</w:t></w:r></w:p>' % t)
    body = "".join(paras)
    doc = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
           '<w:document xmlns:w="http://schemas.openxmlformats.org/'
           'wordprocessingml/2006/main"><w:body>'
           + body +
           '<w:sectPr><w:pgSz w:w="11906" w:h="16838"/>'
           '<w:pgMar w:top="1440" w:right="1440" w:bottom="1440" '
           'w:left="1440" w:header="851" w:footer="992" w:gutter="0"/></w:sectPr>'
           '</w:body></w:document>')
    ct = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
          '<Types xmlns="http://schemas.openxmlformats.org/package/2006/'
          'content-types">'
          '<Default Extension="rels" ContentType="application/vnd.'
          'openxmlformats-package.relationships+xml"/>'
          '<Default Extension="xml" ContentType="application/xml"/>'
          '<Override PartName="/word/document.xml" ContentType="application/'
          'vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>'
          '</Types>')
    rels = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/'
            '2006/relationships">'
            '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/'
            'officeDocument/2006/relationships/officeDocument" '
            'Target="word/document.xml"/>'
            '</Relationships>')
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", ct)
        z.writestr("_rels/.rels", rels)
        z.writestr("word/document.xml", doc)


